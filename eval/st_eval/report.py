"""Render eval/results.md from benchmark results. Every number comes from the run JSON.

Ranking rule (documented in the report itself):
    Q = mean of four category-balanced metrics: IoU, boundary F (DAVIS tolerance), boundary F @3px,
        thin-structure recall.
Category-balanced = mean over the six categories, so 40-image categories don't outweigh 30-image ones.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

CATEGORY_LABELS = {
    "carpet": "carpet (fringe)",
    "jewelry": "gold jewelry",
    "saffron_packaged": "saffron/packaged",
    "glassware": "glassware",
    "handicraft": "handicrafts",
    "clothing_hanger": "clothing/hanger",
}
KEY_TAGS = ["thin_structures", "transparency", "holes", "low_contrast", "patterned_bg", "cluttered_bg", "reflective", "cast_shadow"]


def quality_score(res: dict) -> float:
    b = res["metrics_balanced"]
    vals = [b.get("iou"), b.get("bf"), b.get("bf_3px"), b.get("thin_recall")]
    vals = [v for v in vals if v is not None and not math.isnan(v)]
    return sum(vals) / len(vals) if vals else float("nan")


def _f(v, nd=3):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "–"
    return f"{v:.{nd}f}"


def ok_results(results: dict) -> list[tuple[str, dict]]:
    return [(k, v) for k, v in results.items() if v.get("status") == "ok" and "metrics_balanced" in v]


def best_throughput(res: dict) -> tuple[float, str]:
    """Best images/s among batch sizes that fit in physical VRAM (spilled runs don't count)."""
    best, at = 0.0, "–"
    for bs, s in res.get("throughput", {}).items():
        if s.get("status") == "ok" and not s.get("vram_spill") and s["images_per_s"] > best:
            best, at = s["images_per_s"], bs
    return best, at


def pareto(models: list[tuple[str, dict]]) -> list[str]:
    pts = [(k, quality_score(v), best_throughput(v)[0]) for k, v in models if not v.get("partial")]
    front = []
    for k, q, t in pts:
        if not any((q2 >= q and t2 >= t) and (q2 > q or t2 > t) for _, q2, t2 in pts):
            front.append(k)
    return front


def _precision_cell(v: dict) -> str:
    p = v.get("precision") or v.get("requested_precision") or ""
    req = v.get("requested_precision")
    return f"{p} (asked {req})" if req and req != p else p


def render_report(bundle: dict, analysis_path: Path | None = None) -> str:
    run, results = bundle["run"], bundle["models"]
    hw = run.get("hardware", {})
    ok = sorted(ok_results(results), key=lambda kv: -quality_score(kv[1]))
    L: list[str] = []
    L.append("# Background-removal model comparison\n")
    L.append("> Generated by `make bench` (`python -m st_eval.bench`). **Do not edit by hand**; hand-written analysis lives in "
             "`eval/analysis.md` and is appended at the end.\n")
    L.append("## Run\n")
    ds = run.get("dataset", {})
    L.append(f"- **Created:** {run.get('created_at')} · git `{run.get('git_commit')}`")
    L.append(f"- **Dataset:** `{ds.get('generator_version')}` seed {ds.get('seed')}, **{run.get('n_images')} images** "
             f"({', '.join(f'{c} {n}' for c, n in ds.get('counts', {}).items())}). **Synthetic proxy**, see `docs/dataset-gap.md`.")
    L.append(f"- **Hardware:** {hw.get('gpu', 'no GPU')} ({hw.get('gpu_vram_gb', '?')} GB, compute {hw.get('gpu_capability', '?')}, "
             f"driver {hw.get('nvidia_driver', '?')}, power limit {hw.get('gpu_power_limit_w', '?')} W) · {hw.get('cpu')} · "
             f"{hw.get('cpu_cores_logical', '?')} threads · {hw.get('ram_gb', '?')} GB RAM · torch {hw.get('torch')} / CUDA {hw.get('cuda_runtime')}")
    if (hw.get("gpu_vram_gb") or 99) < 16:
        L.append("- ⚠️ **Not the target hardware.** Measured on a small consumer GPU, not an RTX 3090/4090 (24 GB). Accuracy "
                 "transfers as-is; speed, batch limits and VRAM headroom do **not** (HUMAN_NEEDED H-001).")
    notes = {v.get("precision_note") for _, v in results.items() if v.get("precision_note")}
    for n in sorted(notes):
        L.append(f"- ⚠️ Precision: {n}.")
    L.append(f"- Batch sizes swept: {run.get('batch_sizes')}; ~{run.get('sweep_seconds')} s per batch size. "
             "\"spill\" = PyTorch peak exceeded physical VRAM; the Windows driver silently pages into system RAM instead of "
             "raising OOM, so those timings are not representative and larger batches were skipped.\n")

    failed = [(k, v) for k, v in results.items() if v.get("status") != "ok"]

    L.append("## 1. Ranking by quality\n")
    L.append("Q = mean of category-balanced **IoU**, **boundary F** (DAVIS tolerance: 0.8% of the image diagonal), "
             "**boundary F @ 3 px**, and **thin-structure recall** (recall on ground-truth parts < 7 px wide: fringe, chains, hooks). "
             "Higher is better. Band MAE = alpha error within 10 px of the true edge (lower is better).\n")
    L.append("| # | model | precision | input | images | Q | IoU | BF | BF@3px | thin recall | band MAE | worst category (IoU) |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for i, (k, v) in enumerate(ok, 1):
        b = v["metrics_balanced"]
        cats = {c: m for c, m in v["metrics"].items() if c != "all"}
        worst = min(cats.items(), key=lambda kv: kv[1]["iou"])
        size = v.get("input_size")
        n = f"{v.get('n_images')}{' (partial)' if v.get('partial') else ''}"
        L.append(f"| {i} | `{k}` | {_precision_cell(v)} | {size[0] if size else 'dyn'} | {n} | **{_f(quality_score(v))}** | {_f(b['iou'])} | "
                 f"{_f(b['bf'])} | {_f(b['bf_3px'])} | {_f(b['thin_recall'])} | {_f(b['alpha_mae_band'])} | "
                 f"{CATEGORY_LABELS.get(worst[0], worst[0])} ({_f(worst[1]['iou'])}) |")
    for k, v in failed:
        L.append(f"| – | `{k}` | {_precision_cell(v)} | | | **{v.get('status')}** | | | | | | {str(v.get('error', ''))[:90]} |")
    L.append("")

    L.append("## 2. Per category (IoU / BF@3px / thin recall)\n")
    cats = list(CATEGORY_LABELS)
    L.append("| model | " + " | ".join(CATEGORY_LABELS[c] for c in cats) + " |")
    L.append("|---|" + "---|" * len(cats))
    for k, v in ok:
        cells = []
        for c in cats:
            m = v["metrics"].get(c)
            cells.append(f"{_f(m['iou'], 2)} / {_f(m['bf_3px'], 2)} / {_f(m['thin_recall'], 2)}" if m else "–")
        L.append(f"| `{k}` | " + " | ".join(cells) + " |")
    L.append("")

    L.append("## 3. Hard-case tags (IoU / BF@3px)\n")
    ref = next((v for _, v in ok if not v.get("partial")), ok[0][1] if ok else {})
    tags = [t for t in KEY_TAGS if any(t in v.get("metrics_by_tag", {}) for _, v in ok)]
    L.append("| model | " + " | ".join(f"{t} (n={int(ref.get('metrics_by_tag', {}).get(t, {}).get('n', 0))})" for t in tags) + " |")
    L.append("|---|" + "---|" * len(tags))
    for k, v in ok:
        cells = []
        for t in tags:
            m = v["metrics_by_tag"].get(t)
            cells.append(f"{_f(m['iou'], 2)} / {_f(m['bf_3px'], 2)}" if m else "–")
        L.append(f"| `{k}` | " + " | ".join(cells) + " |")
    L.append("")

    L.append("## 4. Latency and memory (batch size 1, end-to-end)\n")
    L.append("End-to-end = CPU resize + upload + forward + upsample to original size + download, on real benchmark images "
             "(1080×1350, 1200×1200, 1280×960, 960×1280). Forward = GPU forward only. Peak VRAM = PyTorch allocator peak "
             "during the accuracy pass (NVML device-level delta in parentheses).\n")
    L.append("| model | p50 ms | p90 ms | p99 ms | forward p50 ms | preprocess ms | postprocess ms | weights MB | peak VRAM MB | load s |")
    L.append("|---|---|---|---|---|---|---|---|---|---|")
    for k, v in ok:
        lt = v["latency_bs1_ms"]
        spill = " ⚠️ spill" if v.get("vram_spill_bs1") else ""
        L.append(f"| `{k}` | {_f(lt['total']['p50'], 0)} | {_f(lt['total']['p90'], 0)} | {_f(lt['total']['p99'], 0)} | "
                 f"{_f(lt['forward']['p50'], 0)} | {_f(lt['preprocess_p50'], 0)} | {_f(lt['postprocess_p50'], 0)} | "
                 f"{_f(v.get('weights_vram_mb'), 0)} | {_f(v.get('accuracy_peak_torch_mb'), 0)} ({_f(v.get('accuracy_peak_device_mb'), 0)}){spill} | {v.get('load_s')} |")
    L.append("")

    bss = run.get("batch_sizes", [])
    L.append("## 5. Throughput by batch size (images/s · peak VRAM MB)\n")
    L.append("| model | " + " | ".join(f"bs={b}" for b in bss) + " | best (in VRAM) |")
    L.append("|---|" + "---|" * (len(bss) + 1))
    for k, v in ok:
        cells = []
        for b in bss:
            s = v.get("throughput", {}).get(str(b), {})
            st = s.get("status")
            if st == "ok":
                cells.append(f"{s['images_per_s']:.2f} · {s['peak_torch_mb']:.0f}{' ⚠️ spill' if s.get('vram_spill') else ''}")
            elif st == "oom":
                cells.append("**OOM**")
            elif st in ("skipped_after_oom", "skipped_after_vram_spill"):
                cells.append("skipped")
            else:
                cells.append(st or "–")
        t, at = best_throughput(v)
        L.append(f"| `{k}` | " + " | ".join(cells) + f" | {t:.2f} @ bs={at} |")
    L.append("")

    L.append("## 6. Automatic recommendation\n")
    if ok:
        q_leader = ok[0]
        front = pareto(ok)
        full = [(k, v) for k, v in ok if not v.get("partial")]
        fastest = max(full or ok, key=lambda kv: best_throughput(kv[1])[0])
        L.append(f"- **Quality leader:** `{q_leader[0]}` (Q = {_f(quality_score(q_leader[1]))}"
                 f"{', partial subset' if q_leader[1].get('partial') else ''}).")
        L.append(f"- **Throughput leader (fits in VRAM):** `{fastest[0]}` ({best_throughput(fastest[1])[0]:.2f} img/s, "
                 f"Q = {_f(quality_score(fastest[1]))}).")
        L.append("- **Pareto-optimal (quality vs. throughput on this GPU, full-set runs):** " + ", ".join(f"`{k}`" for k in front) + ".")
        near = [k for k, v in full if quality_score(v) >= quality_score((full or ok)[0][1]) - 0.01]
        if len(near) > 1:
            best_fast = max(near, key=lambda k: best_throughput(results[k])[0])
            L.append(f"- Full-set models within 0.01 Q of the best: {', '.join(f'`{k}`' for k in near)}; fastest of those: `{best_fast}`.")
        L.append("- Decision and reasoning: see **Analysis** below.")
    else:
        L.append("No model completed.")
    L.append("")

    if analysis_path and Path(analysis_path).exists():
        L.append("---\n")
        L.append(Path(analysis_path).read_text(encoding="utf-8"))
    return "\n".join(L) + "\n"


def load_run(run_dir: Path) -> dict:
    run = json.loads((run_dir / "run.json").read_text(encoding="utf-8"))
    models = {}
    for p in sorted((run_dir / "models").glob("*.json")):
        r = json.loads(p.read_text(encoding="utf-8"))
        models[r["spec"]] = r
    order = run.get("models_order") or list(models)
    order = [k for k in order if k in models] + [k for k in models if k not in order]
    return {"run": run, "models": {k: models[k] for k in order}}


def main() -> None:
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("run_dir", type=Path)
    ap.add_argument("--out", type=Path, default=Path("eval/results.md"))
    ap.add_argument("--analysis", type=Path, default=Path("eval/analysis.md"))
    args = ap.parse_args()
    args.out.write_text(render_report(load_run(args.run_dir), args.analysis), encoding="utf-8")
    print("wrote", args.out)


if __name__ == "__main__":
    main()
